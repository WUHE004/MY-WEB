-- ============================================================
-- 005: 直播选品表唯一约束修复(跨天无法重选 bug)
-- ============================================================
-- 背景:
--   建表时 UNIQUE(member_name, sale_id) 表示"同一成员对同一编号终身只能选一次"。
--   9-27 改版后选品按天独立记录(同编号每天可选、历史记录保留),
--   但数据库层的旧约束没同步删除, 导致"以前选过的商品今天重新选"插入时
--   报 duplicate key(23505), 前端表现为选品按钮闪跳"选不过去"。
-- 修复:
--   删除旧约束。同天防重复由 API 层查重保证(同编号同一天只保留一条,
--   已上线验证), 跨天重选从此不再受限。
-- 影响范围:
--   只删约束, 不动任何表结构/数据行, 可随时执行, 重复执行安全。

ALTER TABLE public.live_selections
  DROP CONSTRAINT IF EXISTS live_selections_member_name_sale_id_key;
